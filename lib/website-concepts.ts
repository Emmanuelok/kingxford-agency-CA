export function filterWebsiteConcepts(group: ConceptGroup, query: string) {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return websiteConcepts.filter((concept) => {
    const text = `${concept.name} ${concept.sector} ${concept.group} ${concept.tagline}`.toLocaleLowerCase();
    return (group === "All concepts" || concept.group === group) && terms.every((term) => text.includes(term));
  });
}
